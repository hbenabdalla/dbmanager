#!/usr/bin/env bash
# Real-engine integration tests for DBManager adapters (Linux / macOS / WSL).
# See scripts/integration-test.ps1 for the description; usage:
#   scripts/integration-test.sh [postgresql mysql mariadb mssql oracle db2 timeseries identity vault]
#   scripts/integration-test.sh --down
#   IT_PYTEST_ADDOPTS='-k backup' scripts/integration-test.sh ...   # only matching tests
# Starting a vendor image means accepting that vendor's license (SQL Server Developer EULA,
# Oracle Free Use Terms for XE, IBM Db2 Community Edition).
set -uo pipefail
cd "$(dirname "$0")/.."
C=(docker compose --progress plain -f docker-compose.test.yml --env-file .env.test)
declare -A SVC=([postgresql]=pg16 [mysql]=mysql [mariadb]=mariadb [mssql]=mssql [oracle]=oracle [db2]=db2 [timeseries]=victoriametrics
  [identity]="openldap keycloak" [vault]=vault)
declare -A HOSTENV=([postgresql]=DBM_IT_PG_HOST=pg16 [mysql]=DBM_IT_MYSQL_HOST=mysql [mariadb]=DBM_IT_MARIADB_HOST=mariadb
  [mssql]=DBM_IT_MSSQL_HOST=mssql [oracle]=DBM_IT_ORACLE_HOST=oracle [db2]=DBM_IT_DB2_HOST=db2
  [timeseries]=DBM_IT_VM_URL=http://victoriametrics:8428
  [identity]="DBM_IT_LDAP_HOST=openldap DBM_IT_KEYCLOAK_URL=http://keycloak:8080" [vault]=DBM_IT_VAULT_ADDR=http://vault:8200)
ORDER=(postgresql mysql mariadb mssql oracle db2 timeseries identity vault)
KEYS=(IT_PG_PASSWORD IT_MYSQL_PASSWORD IT_MARIADB_PASSWORD IT_MSSQL_SA_PASSWORD IT_ORACLE_PASSWORD
      IT_DB2_PASSWORD IT_DB2_MON_PASSWORD IT_DB2_ADM_PASSWORD IT_DB2_RO_PASSWORD IT_DB2_BK_PASSWORD
      IT_LDAP_ADMIN_PASSWORD IT_KEYCLOAK_ADMIN_PASSWORD IT_VAULT_TOKEN)

secret() { echo "It$(od -An -N12 -tx1 /dev/urandom | tr -d ' \n')9"; }
if [ ! -f .env.test ]; then
  echo "# generated by scripts/integration-test.sh - test containers only, never commit" > .env.test
  chmod 600 .env.test
  echo "created .env.test with generated passwords"
fi
for k in "${KEYS[@]}"; do  # keys added by newer versions are appended to an existing file
  grep -q "^$k=" .env.test || echo "$k=$(secret)" >> .env.test
done

if [ "${1:-}" = "--down" ]; then
  exec "${C[@]}" --profile all --profile oracle-ee --profile runner down -v --remove-orphans
fi
ENGINES=("$@"); [ ${#ENGINES[@]} -eq 0 ] && ENGINES=("${ORDER[@]}")
PROFILES=(); SERVICES=(); ENVS=()
for e in "${ENGINES[@]}"; do
  [ -n "${SVC[$e]:-}" ] || { echo "unknown engine '$e' (use: ${ORDER[*]})" >&2; exit 2; }
  PROFILES+=(--profile "$e")
  for s in ${SVC[$e]}; do SERVICES+=("$s"); done
  for v in ${HOSTENV[$e]}; do ENVS+=(-e "$v"); done
done
mkdir -p integration-results backend/app/data
LOG=integration-results/run.log
echo "== $(date -u +%FT%TZ) engines: ${ENGINES[*]}" > "$LOG"
run() { echo "+ $*"; "$@" 2>&1 | tee -a "$LOG"; return "${PIPESTATUS[0]}"; }

# the runner image is built first: it also generates the test TLS material for MySQL/MariaDB
run "${C[@]}" --profile runner build it-runner || { echo "building the test runner failed" >&2; exit 1; }
if [[ " ${ENGINES[*]} " == *" mysql "* || " ${ENGINES[*]} " == *" mariadb "* ]]; then
  run "${C[@]}" --profile certs run --rm tls-certs || echo "WARNING: no test TLS material; certificate checks will fail"
fi
run "${C[@]}" "${PROFILES[@]}" up -d --wait --wait-timeout 2400 "${SERVICES[@]}" \
  || echo "WARNING: an engine did not become healthy; its tests will report the failure"
if [[ " ${ENGINES[*]} " == *" db2 "* ]]; then
  # bounded: a setup step must never block the whole run (the script itself also gives up on locks)
  run "${C[@]}" --profile db2 exec -T db2 timeout 900 bash /var/custom/dbm-it-users.sh \
    || echo "WARNING: Db2 user setup did not finish; Db2 tests may skip or fail (see /database/dbm-it-users.log in the db2 container)"
fi
if [[ " ${ENGINES[*]} " == *" identity "* ]]; then
  # the service account must be able to search users and groups (idempotent)
  run "${C[@]}" --profile identity exec -T openldap ldapmodify -Y EXTERNAL -Q -H ldapi:/// \
    -f /container/service/slapd/assets/config/bootstrap/ldif/custom/40-dbm-it-acl.ldif \
    || echo "WARNING: could not set the OpenLDAP access rules; LDAP tests may fail"
fi
run "${C[@]}" --profile runner run --rm "${ENVS[@]}" it-runner; rc=$?
[ -f integration-results/real-engine-matrix.md ] && tee -a "$LOG" < integration-results/real-engine-matrix.md
[ "${KEEP_RUNNING:-0}" = 1 ] || "${C[@]}" "${PROFILES[@]}" stop >/dev/null 2>&1
echo "== exit $rc" >> "$LOG"
exit $rc
