<#
.SYNOPSIS
  Real-engine integration tests for DB Manager adapters (Windows PowerShell 5.1+ / PowerShell 7).

.DESCRIPTION
  1. creates .env.test with generated passwords (once; never committed)
  2. starts the requested engines from docker-compose.test.yml (official vendor images) and waits
     until each one is really ready (health checks run SQL)
  3. creates the Db2 least-privilege OS identities
  4. builds the backend image's "it" target (all drivers, incl. Microsoft ODBC Driver 18)
  5. runs the real-engine suite and writes integration-results\real-engine-matrix.{json,md}
     and merges the result into backend\app\data\real_engine_validation.json

  Starting a vendor image means accepting that vendor's license: SQL Server Developer (EULA),
  Oracle Database XE (Oracle Free Use Terms), IBM Db2 Community Edition.

.EXAMPLE
  .\scripts\integration-test.ps1                       # all engines
  .\scripts\integration-test.ps1 mssql oracle db2
  .\scripts\integration-test.ps1 -Down                 # stop and remove the test containers + volumes
#>
param(
  [Parameter(ValueFromRemainingArguments = $true)][string[]]$Engines,
  [switch]$Down,
  [switch]$KeepRunning
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
# plain progress: readable log lines instead of redrawn progress bars
$compose = @('compose', '--progress', 'plain', '-f', 'docker-compose.test.yml', '--env-file', '.env.test')
$services = [ordered]@{
  postgresql = 'pg16'; mysql = 'mysql'; mariadb = 'mariadb'; mssql = 'mssql'
  oracle = 'oracle'; db2 = 'db2'; timeseries = 'victoriametrics'
  identity = @('openldap', 'keycloak'); vault = 'vault'
}
$hostEnv = @{
  postgresql = 'DBM_IT_PG_HOST=pg16'; mysql = 'DBM_IT_MYSQL_HOST=mysql'; mariadb = 'DBM_IT_MARIADB_HOST=mariadb'
  mssql = 'DBM_IT_MSSQL_HOST=mssql'; oracle = 'DBM_IT_ORACLE_HOST=oracle'; db2 = 'DBM_IT_DB2_HOST=db2'
  timeseries = 'DBM_IT_VM_URL=http://victoriametrics:8428'
  identity = @('DBM_IT_LDAP_HOST=openldap', 'DBM_IT_KEYCLOAK_URL=http://keycloak:8080')
  vault = 'DBM_IT_VAULT_ADDR=http://vault:8200'
}

function New-Secret([int]$bytes = 12) {
  $b = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  # letters + digits only (no shell/SQL quoting issues); "It" + hex satisfies SQL Server's policy
  return 'It' + (($b | ForEach-Object { $_.ToString('x2') }) -join '') + '9'
}

$envFile = Join-Path $root '.env.test'
$keys = 'IT_PG_PASSWORD', 'IT_MYSQL_PASSWORD', 'IT_MARIADB_PASSWORD', 'IT_MSSQL_SA_PASSWORD', 'IT_ORACLE_PASSWORD',
        'IT_DB2_PASSWORD', 'IT_DB2_MON_PASSWORD', 'IT_DB2_ADM_PASSWORD', 'IT_DB2_RO_PASSWORD',
        'IT_LDAP_ADMIN_PASSWORD', 'IT_KEYCLOAK_ADMIN_PASSWORD', 'IT_VAULT_TOKEN'
if (-not (Test-Path $envFile)) {
  [System.IO.File]::WriteAllLines($envFile, @('# generated by scripts/integration-test.ps1 - test containers only, never commit'))
  Write-Host 'created .env.test with generated passwords'
}
# keys added by newer versions are appended to an existing file
$existing = [System.IO.File]::ReadAllLines($envFile)
$missing = $keys | Where-Object { $k = $_; -not ($existing | Where-Object { $_.StartsWith("$k=") }) }
if ($missing) {
  [System.IO.File]::AppendAllLines($envFile, [string[]]($missing | ForEach-Object { "$_=$(New-Secret)" }))
}

if ($Down) {
  & docker @compose --profile all --profile oracle-ee --profile runner down -v --remove-orphans
  exit $LASTEXITCODE
}

if (-not $Engines -or $Engines.Count -eq 0) { $Engines = @($services.Keys) }
foreach ($e in $Engines) { if (-not $services.Contains($e)) { throw "unknown engine '$e' (use: $($services.Keys -join ', '))" } }

New-Item -ItemType Directory -Force integration-results, backend\app\data | Out-Null
$log = Join-Path $root 'integration-results\run.log'
$utf8 = New-Object System.Text.UTF8Encoding $false   # UTF-8 without BOM on Windows PowerShell 5.1 too
function Write-Log([string]$line) { [System.IO.File]::AppendAllText($log, $line + "`n", $utf8) }
[System.IO.File]::WriteAllText($log, "== $(Get-Date -Format o) engines: $($Engines -join ' ')`n", $utf8)

function Invoke-Docker([string[]]$a) {
  Write-Host "docker $($a -join ' ')"
  # docker writes progress to stderr: do not let Windows PowerShell turn it into terminating errors
  $prev = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
  try {
    Write-Log "+ docker $($a -join ' ')"
    & docker @a 2>&1 | ForEach-Object { $l = "$_"; Write-Log $l; $l } | Out-Host
    return $LASTEXITCODE
  } finally { $ErrorActionPreference = $prev }
}

$svc = $Engines | ForEach-Object { $services[$_] } | ForEach-Object { $_ }
$profiles = $Engines | ForEach-Object { '--profile'; $_ }
# first start of Oracle XE / Db2 creates the database: allow up to 40 minutes
$rc = Invoke-Docker ($compose + $profiles + @('up', '-d', '--wait', '--wait-timeout', '2400') + $svc)
if ($rc -ne 0) {
  Write-Warning 'an engine did not become healthy; its tests will report the failure (see docker compose logs)'
}

if ($Engines -contains 'db2') {
  $rc = Invoke-Docker ($compose + @('--profile', 'db2', 'exec', '-T', 'db2', 'bash', '/var/custom/dbm-it-users.sh'))
}

$rc = Invoke-Docker ($compose + @('--profile', 'runner', 'build', 'it-runner'))
if ($rc -ne 0) { throw 'building the test runner image failed (see integration-results\run.log)' }

$envArgs = $Engines | ForEach-Object { foreach ($v in @($hostEnv[$_])) { '-e'; $v } }
$rc = Invoke-Docker ($compose + @('--profile', 'runner', 'run', '--rm') + $envArgs + @('it-runner'))
$testRc = $rc

if (Test-Path integration-results\real-engine-matrix.md) {
  Get-Content integration-results\real-engine-matrix.md | ForEach-Object { Write-Log $_; $_ } | Out-Host
}
if (-not $KeepRunning) {
  Invoke-Docker ($compose + $profiles + @('stop')) | Out-Null
}
Write-Log "== exit $testRc"
exit $testRc
