"""Guarded administration actions on managed databases.

Preview → review → confirm → execute → audit. Statements are generated by the engine's
adapter (never one generic SQL string), shown with secrets masked, executed with the
*administration* credential, and refused for servers registered as Monitoring only.
"""

from __future__ import annotations

import uuid
from typing import Any

from fastapi import APIRouter
from pydantic import BaseModel, Field

from app.adapters import admin as A
from app.adapters.base import AdapterNotSupported, Capability, CapabilityLevel, ConnectionSpec
from app.adapters.registry import adapter_class_for
from app.api.deps import DB, CurrentPrincipal, load_server
from app.core.errors import ConfirmationRequired, ValidationFailed
from app.domain.risk import RiskClass
from app.models import Server
from app.services import audit, secrets
from app.services.authz import server_ref
from app.services.connections import adapter_for, management_mode, require_administration, require_capability, target

router = APIRouter(tags=["administration"])
SECRET_PARAMS = {"password"}


class AdminRequest(BaseModel):
    action: str
    params: dict[str, Any] = Field(default_factory=dict)
    confirm: str | None = None
    reason: str | None = Field(None, max_length=1000)


def _confirmation(s: Server, risk: str) -> str | None:
    is_prod = bool(s.environment and s.environment.tier == "production")
    if risk == RiskClass.DESTRUCTIVE.value or (is_prod and risk != RiskClass.READ.value):
        return s.name
    if risk == RiskClass.PRIVILEGED_CHANGE.value:
        return "CONFIRM"
    return None


def _build(s: Server, body: AdminRequest) -> A.AdminStatement:
    if body.action not in A.ACTIONS:
        raise ValidationFailed(f"unknown action {body.action!r}", details={"actions": sorted(A.ACTIONS)})
    cls = adapter_class_for(s.engine)
    adapter = cls(ConnectionSpec(host=s.host, port=s.port, database=s.default_database, options=dict(s.options or {})))
    try:
        return adapter.build_admin(body.action, body.params)
    except A.AdminValidationError as exc:
        raise ValidationFailed(str(exc)) from exc
    except AdapterNotSupported as exc:
        raise ValidationFailed(f"{body.action} is not available for {cls.display_name}: {exc.reason}") from exc


def _safe_params(params: dict[str, Any]) -> dict[str, Any]:
    return {k: ("********" if k in SECRET_PARAMS else v) for k, v in params.items()}


def _check_permission(p: Any, s: Server, action: str, database: str | None) -> None:
    perm = A.ACTIONS[action]["permission"]
    p.authz.require(perm, server_ref(s, database))


@router.get("/servers/{server_id}/admin/actions", summary="Administration actions available for this server")
async def list_actions(server_id: uuid.UUID, db: DB, p: CurrentPrincipal) -> dict[str, Any]:
    s = await load_server(db, p, server_id)
    ref = server_ref(s)
    entry = (s.capabilities or {}).get(Capability.ADMINISTRATION.value) or {}
    level = entry.get("level") or adapter_class_for(s.engine).capability_profile()[Capability.ADMINISTRATION].level
    cred = None if s.is_simulated else await secrets.get_credential(db, s.id, "admin")
    blockers = []
    if s.is_simulated:
        blockers.append("simulated server: nothing is ever executed")
    if management_mode(s) == "monitoring":
        blockers.append("registered as Monitoring only")
    if not CapabilityLevel(level).usable:
        blockers.append(entry.get("note") or "administration is not available for this engine")
    if cred is None and not s.is_simulated:
        blockers.append("no administration credential configured")
    return {
        "management_mode": management_mode(s),
        "available": not blockers,
        "blockers": blockers,
        "actions": [
            {
                "action": k,
                "label": v["label"],
                "risk": v["risk"],
                "permission": v["permission"],
                "params": v["params"],
                "allowed": p.authz.has(v["permission"], ref),
            }
            for k, v in A.ACTIONS.items()
        ],
    }


@router.post("/servers/{server_id}/admin/preview", summary="Generate and review the statements for an action")
async def preview(server_id: uuid.UUID, body: AdminRequest, db: DB, p: CurrentPrincipal) -> dict[str, Any]:
    s = await load_server(db, p, server_id)
    stmt = _build(s, body)
    _check_permission(p, s, body.action, stmt.database or body.params.get("database"))
    exp = _confirmation(s, stmt.risk)
    return {
        **stmt.summary(),
        "confirmation": None if exp is None else ("server name" if exp == s.name else exp),
        "management_mode": management_mode(s),
        "executable": management_mode(s) == "administration" and not s.is_simulated,
    }


@router.post("/servers/{server_id}/admin/execute", summary="Execute a reviewed administration action")
async def execute(server_id: uuid.UUID, body: AdminRequest, db: DB, p: CurrentPrincipal) -> dict[str, Any]:
    s = await load_server(db, p, server_id)
    stmt = _build(s, body)
    database = stmt.database or body.params.get("database")
    _check_permission(p, s, body.action, database)
    require_administration(s)
    if s.is_simulated:
        raise ValidationFailed("Simulated servers never execute statements.", code="simulated_server")
    require_capability(s, Capability.ADMINISTRATION)
    exp = _confirmation(s, stmt.risk)
    if exp is not None and body.confirm != exp:
        raise ConfirmationRequired(
            "Review the generated statements and confirm to continue.",
            details={
                "expected": "server name" if exp == s.name else exp,
                "statements": stmt.display,
                "risk": stmt.risk,
            },
        )
    is_prod = bool(s.environment and s.environment.tier == "production")
    if stmt.risk == RiskClass.DESTRUCTIVE.value and is_prod and not body.reason:
        raise ValidationFailed("A change reason is required for destructive actions in production")
    details = {"action": body.action, "params": _safe_params(body.params), "statements": stmt.display}
    try:
        async with target(await adapter_for(db, s, "admin")) as a:
            res = await a.run_admin(stmt)
    except Exception as exc:
        await audit.record(
            f"admin.{body.action}",
            actor=p,
            server=s,
            database=database,
            object_name=stmt.target_object,
            result="failure",
            risk_class=stmt.risk,
            failure_reason=str(exc)[:500],
            change_reason=body.reason,
            details=details,
        )
        raise
    await audit.record(
        f"admin.{body.action}",
        actor=p,
        server=s,
        database=database,
        object_name=stmt.target_object,
        risk_class=stmt.risk,
        change_reason=body.reason,
        details={**details, **res},
    )
    return {"ok": True, **stmt.summary(), **res}
