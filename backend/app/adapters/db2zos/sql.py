"""SQL used by the Db2 for z/OS adapter (Db2 12 and 13 for z/OS).

Only the SYSIBM catalog, real-time statistics tables and SQL statements available to a DRDA
client are used. Instance-level performance data on z/OS (IFI/IFCID traces, SMF, RMF,
statistics/accounting classes) is not reachable through SQL from a remote client and belongs
to z/OS monitors (OMEGAMON, IBM Db2 Administration Foundation, ...).
"""

SERVER_INFO = """
SELECT GETVARIABLE('SYSIBM.VERSION') AS VERSION, GETVARIABLE('SYSIBM.SSID') AS SSID,
       GETVARIABLE('SYSIBM.DATA_SHARING_GROUP_NAME') AS DSGROUP, CURRENT SERVER AS LOCATION,
       CURRENT SQLID AS SQLID, USER AS AUTHID, CURRENT MEMBER AS MEMBER_NAME
FROM SYSIBM.SYSDUMMY1
"""
APP_COMPAT = "SELECT CURRENT APPLICATION COMPATIBILITY AS APPLCOMPAT FROM SYSIBM.SYSDUMMY1"

DATABASES = """
SELECT NAME, CREATOR, STGROUP, BPOOL, TYPE, CREATEDTS, ENCODING_SCHEME
FROM SYSIBM.SYSDATABASE
ORDER BY NAME
"""
DATABASE_SPACE = """
SELECT DBNAME, SUM(SPACE) AS SPACE_KB FROM SYSIBM.SYSTABLESPACESTATS GROUP BY DBNAME
"""
SCHEMAS = """
SELECT CREATOR, TYPE, COUNT(*) AS N FROM SYSIBM.SYSTABLES GROUP BY CREATOR, TYPE
"""
ROUTINE_SCHEMAS = "SELECT SCHEMA, ROUTINETYPE, COUNT(*) AS N FROM SYSIBM.SYSROUTINES GROUP BY SCHEMA, ROUTINETYPE"
TABLES = """
SELECT NAME, TYPE, DBNAME, TSNAME, CARDF, NPAGESF, STATSTIME, CREATEDTS, ALTEREDTS
FROM SYSIBM.SYSTABLES
WHERE CREATOR = ? AND TYPE IN ({types})
ORDER BY NAME
"""
INDEXES = """
SELECT NAME, TBNAME, UNIQUERULE, CLUSTERING, INDEXSPACE, STATSTIME
FROM SYSIBM.SYSINDEXES
WHERE CREATOR = ? {table_filter}
ORDER BY TBNAME, NAME
"""
ROUTINES = "SELECT NAME, ROUTINETYPE, CREATEDTS, ORIGIN FROM SYSIBM.SYSROUTINES WHERE SCHEMA = ? AND ROUTINETYPE IN ({types}) ORDER BY NAME"
TRIGGERS = "SELECT NAME, TBNAME, TRIGTIME, TRIGEVENT FROM SYSIBM.SYSTRIGGERS WHERE SCHEMA = ? ORDER BY NAME"
SEQUENCES = "SELECT NAME, START, INCREMENT FROM SYSIBM.SYSSEQUENCES WHERE SCHEMA = ? AND SEQTYPE = 'S' ORDER BY NAME"
COLUMNS = """
SELECT NAME, COLNO, COLTYPE, LENGTH, SCALE, NULLS, DEFAULT
FROM SYSIBM.SYSCOLUMNS WHERE TBCREATOR = ? AND TBNAME = ? ORDER BY COLNO
"""
TABLE_ROW = (
    "SELECT TYPE, DBNAME, TSNAME, CARDF, NPAGESF, STATSTIME FROM SYSIBM.SYSTABLES WHERE CREATOR = ? AND NAME = ?"
)
TABLE_CARD = "SELECT CARDF FROM SYSIBM.SYSTABLES WHERE CREATOR = ? AND NAME = ?"

# --- authorization (catalog grants; RACF/ACF2/Top Secret are not visible through SQL) --------
USERAUTH = """
SELECT GRANTEE, GRANTEETYPE, SYSADMAUTH, SYSCTRLAUTH, SYSOPRAUTH, BINDADDAUTH, CREATEDBAAUTH,
       SECURITYADMAUTH, DATAACCESSAUTH, ACCESSCTRLAUTH, SQLADMAUTH, EXPLAINAUTH
FROM SYSIBM.SYSUSERAUTH
"""
DBAUTH = """
SELECT GRANTEE, NAME, DBADMAUTH, DBCTRLAUTH, DBMAINTAUTH, CREATETABAUTH, CREATETSAUTH
FROM SYSIBM.SYSDBAUTH
"""
TABAUTH = """
SELECT GRANTOR, GRANTEE, GRANTEETYPE, TCREATOR, TTNAME, SELECTAUTH, INSERTAUTH, UPDATEAUTH, DELETEAUTH, ALTERAUTH,
       INDEXAUTH
FROM SYSIBM.SYSTABAUTH
WHERE TCREATOR NOT LIKE 'SYS%'
FETCH FIRST {limit} ROWS ONLY
"""
PUBLIC_TABLE_GRANTS = """
SELECT COUNT(*) AS N FROM SYSIBM.SYSTABAUTH
WHERE GRANTEE = 'PUBLIC' AND (SELECTAUTH <> ' ' OR UPDATEAUTH <> ' ' OR DELETEAUTH <> ' ' OR INSERTAUTH <> ' ')
  AND TCREATOR NOT LIKE 'SYS%'
"""
ROLES = "SELECT NAME, DEFINER, CREATEDTS FROM SYSIBM.SYSROLES ORDER BY NAME"
TRUSTED_CONTEXTS = "SELECT NAME, ENABLED, DEFAULTROLE, SYSTEMAUTHID FROM SYSIBM.SYSCONTEXT"

# --- real-time statistics (DSNACCOX-style recommendations; never executed) --------------------
RTS_TABLESPACES = """
SELECT DBNAME, NAME, PARTITION, TOTALROWS, NACTIVE, SPACE, REORGLASTTIME, REORGINSERTS, REORGDELETES,
       REORGUPDATES, REORGUNCLUSTINS, REORGMASSDELETE, STATSLASTTIME, STATSINSERTS, STATSDELETES, STATSUPDATES,
       COPYLASTTIME, COPYUPDATEDPAGES, UPDATESTATSTIME
FROM SYSIBM.SYSTABLESPACESTATS
WHERE DBNAME NOT LIKE 'DSN%'
ORDER BY SPACE DESC
FETCH FIRST 500 ROWS ONLY
"""
TOP_SPACES = """
SELECT DBNAME, NAME, SUM(SPACE) AS SPACE_KB, SUM(TOTALROWS) AS TOTALROWS
FROM SYSIBM.SYSTABLESPACESTATS
GROUP BY DBNAME, NAME
ORDER BY SUM(SPACE) DESC
FETCH FIRST 20 ROWS ONLY
"""

