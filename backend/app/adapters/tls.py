"""TLS settings shared by the adapters.

``tls_mode`` uses the same vocabulary for every engine (disable | prefer | require |
verify-ca | verify-full); each adapter translates it into its driver's options.
"""

from __future__ import annotations

import os
import ssl
import tempfile

MODES = ("disable", "prefer", "require", "verify-ca", "verify-full")


def ssl_context(mode: str, ca_pem: str | None) -> ssl.SSLContext | None:
    """Python ``SSLContext`` for drivers that accept one (PyMySQL, python-oracledb).

    ``None`` means "do not force TLS" (disable / prefer without a CA)."""
    mode = (mode or "prefer").lower()
    if mode == "disable":
        return None
    if mode == "prefer" and not ca_pem:
        return None
    ctx = ssl.create_default_context(cadata=ca_pem) if ca_pem else ssl.create_default_context()
    # Python 3.13 sets VERIFY_X509_STRICT; self-signed server certificates generated by MySQL
    # and Db2 instances do not pass it although they are valid for verify-ca.
    ctx.verify_flags &= ~getattr(ssl, "VERIFY_X509_STRICT", 0)
    if mode in ("prefer", "require"):
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_REQUIRED if ca_pem else ssl.CERT_NONE
    elif mode == "verify-ca":
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_REQUIRED
    else:  # verify-full
        ctx.check_hostname = True
        ctx.verify_mode = ssl.CERT_REQUIRED
    return ctx


def verifies_certificate(mode: str) -> bool:
    return (mode or "").lower() in ("verify-ca", "verify-full")


def requires_tls(mode: str) -> bool:
    return (mode or "").lower() in ("require", "verify-ca", "verify-full")


class CAFile:
    """Writes a CA bundle to a private temporary file for drivers that only accept a path
    (ODBC ``ServerCertificate``, Db2 ``SSLServerCertificate``). Removed on close."""

    def __init__(self, pem: str | None):
        self.path: str | None = None
        if pem:
            fd, self.path = tempfile.mkstemp(prefix="dbm-ca-", suffix=".pem")
            with os.fdopen(fd, "w") as f:
                f.write(pem)
            os.chmod(self.path, 0o600)

    def close(self) -> None:
        if self.path:
            try:
                os.unlink(self.path)
            except OSError:
                pass
            self.path = None
