class DemoAdapter(BaseDatabaseAdapter):
    engine = "demo"
    display_name = "Simulated server"
    default_port = 0
    driver = "simulator"
    static_capabilities: ClassVar[CapabilityMap] = {c: cap(FULL, "simulated") for c in Capability} | {
        Capability.LOGS: cap(PARTIAL, "simulated collection log only"),
        Capability.SQL_WORKSPACE: cap(PARTIAL, "simulated: statements are classified but never executed"),
    }

    def __init__(self, spec: ConnectionSpec):
        super().__init__(spec)
        p = spec.demo_profile or {}
        self.sim_engine: str = p.get("engine", "postgresql")
        self.seed: str = p.get("seed", spec.host)
        self.scale: float = float(p.get("scale", 1.0))
        self.scenarios: set[str] = set(p.get("scenarios", []))
        self.role: str = p.get("role", "primary")
        self.size_gb: float = float(p.get("size_gb", 120))
        self.meta = catalog.ENGINE_META.get(self.sim_engine, catalog.ENGINE_META["postgresql"])
        if "outdated_version" in self.scenarios and self.sim_engine in OUTDATED_VERSIONS:
            v, num, full = OUTDATED_VERSIONS[self.sim_engine]
            self.meta = {**self.meta, "version": v, "version_num": num, "version_full": full}
        self.regression_since: datetime | None = None
        if p.get("regression_since"):
            self.regression_since = datetime.fromisoformat(p["regression_since"])
        self._max_conn = MAX_CONN.get(self.sim_engine, 200)
        self.started_at = datetime(2026, 8, 1, 3, 0, tzinfo=UTC) + timedelta(hours=rnd(self.seed, "start", 0, 900))

    # ------------------------------------------------------------------------------------
    async def connect(self) -> None:
        if "down" in self.scenarios:
            raise AdapterConnectionError(
                f"cannot connect to {self.spec.host}:{self.spec.port}: [Errno 111] Connection refused (simulated outage)"
            )

    async def discover_capabilities(self) -> CapabilityMap:
        from app.adapters.registry import adapter_class_for

        real = adapter_class_for(self.sim_engine).engine_profile()
        # Demo mirrors what the real engine offers, so the UI behaves as it will in production.
        caps: CapabilityMap = {}
        for c, s in real.items():
            if s.level.usable or s.level.name.startswith("REQUIRES"):
                caps[c] = cap(FULL if s.level is FULL else PARTIAL, f"simulated · {s.note or s.level.value}")
            else:
                caps[c] = s
        caps[Capability.SQL_WORKSPACE] = cap(PARTIAL, "simulated: statements are classified but never executed")
        return caps

    async def get_server_info(self) -> ServerInfo:
        await self.connect()
        now = datetime.now(UTC)
        return ServerInfo(
            engine=self.sim_engine,
            version=self.meta["version"],
            version_num=self.meta["version_num"],
            edition=self.meta["version_full"],
            started_at=self.started_at,
            uptime_seconds=(now - self.started_at).total_seconds(),
            is_replica=self.role != "primary",
            current_user="dbm_monitor",
            hostname=self.spec.host,
            extra={"version_full": self.meta["version_full"], "simulated": True},
        )

    # ------------------------------------------------------------------------------------
    # metrics
    # ------------------------------------------------------------------------------------
    def metrics_at(self, ts: datetime) -> MetricSnapshot:
        s, sc = self.seed, self.scale
        snap = MetricSnapshot(collected_at=ts)
        g = snap.gauges
        sat = "connection_saturation" in self.scenarios
        conn_base = self._max_conn * (0.78 if sat else 0.32) * min(sc, 2.2)
        total = min(signal(s, "conn", ts, conn_base, amp=0.25 if sat else 0.45), self._max_conn * 0.99)
        active = total * (0.18 + 0.12 * abs(noise(s, "act", ts)))
        idle_txn = max(0.0, 1.5 + 2 * noise(s, "iit", ts)) * (4 if "blocking" in self.scenarios else 1)
        g["connections.total"] = round(total)
        g["connections.active"] = round(active)
        g["connections.idle_in_transaction"] = round(idle_txn)
        g["connections.idle"] = max(round(total - active - idle_txn), 0)
        g["connections.max"] = self._max_conn
        g["connections.utilization"] = round(100 * total / self._max_conn, 2)

        tps = signal(s, "tps", ts, 420 * sc, amp=0.5)
        g["transactions.per_sec"] = round(tps, 2)
        g["commits.per_sec"] = round(tps * 0.985, 2)
        g["rollbacks.per_sec"] = round(tps * 0.015, 2)
        g["query.calls_per_sec"] = round(tps * 3.4, 2)

        pressure = "cache_pressure" in self.scenarios
        hit = (91.5 + 2.2 * noise(s, "hit", ts)) if pressure else (99.35 + 0.4 * noise(s, "hit", ts))
        g["cache.hit_ratio"] = round(min(hit, 99.99), 2)
        g["io.blocks_read_per_sec"] = round(signal(s, "rd", ts, 650 * sc * (6 if pressure else 1)), 2)
        slow = "slow_queries" in self.scenarios
        g["query.mean_latency_ms"] = round(
            signal(
                s,
                "lat",
                ts,
                (21 if pressure else 6.5) * (1.6 if sat else 1) * (5.5 if slow else 1) * self._regression(ts, 0.25),
                amp=0.35,
            ),
            3,
        )

        blocking = "blocking" in self.scenarios
        g["sessions.blocked"] = round(max(1.0, 2.6 + 1.5 * noise(s, "blk", ts))) if blocking else 0
        g["sessions.waiting"] = g["sessions.blocked"]
        g["locks.total"] = round(signal(s, "locks", ts, 60 * sc))
        g["locks.waiting"] = g["sessions.blocked"]
        if "deadlocks" in self.scenarios:
            g["deadlocks.count"] = float(max(0, round(1.6 + 1.6 * noise(s, "dl", ts, 600))))
        else:
            g["deadlocks.count"] = 1.0 if blocking and noise(s, "dl", ts, 900) > 0.85 else 0.0
        g["transactions.longest_seconds"] = round(abs(noise(s, "lx", ts)) * (5400 if blocking else 40), 1)
        g["query.longest_running_seconds"] = round(abs(noise(s, "lq", ts)) * 90, 1)

        temp = "temp_spill" in self.scenarios
        g["temp.bytes_per_sec"] = round(signal(s, "tmp", ts, (48 if temp else 0.4) * 1024**2 * sc), 0)

        if "cpu_saturation" in self.scenarios:
            g["cpu.percent"] = round(min(99.5, 96.8 + 1.3 * noise(s, "cpu", ts) + diurnal(ts)), 2)
        elif "high_cpu" in self.scenarios:
            g["cpu.percent"] = round(88.0 + 2.4 * noise(s, "cpu", ts) + 2 * diurnal(ts), 2)
        else:
            g["cpu.percent"] = round(
                min(82.0, signal(s, "cpu", ts, 34 * min(sc, 1.4) * (1.4 if pressure or sat else 1), amp=0.45)), 2
            )
        mem_total = 64 * GiB * max(sc, 0.5)
        g["memory.total_bytes"] = mem_total
        g["memory.used_bytes"] = round(mem_total * (0.72 + 0.05 * noise(s, "mem", ts)))

        days = (ts - datetime(2026, 1, 1, tzinfo=UTC)).total_seconds() / 86400
        growth = rnd(s, "growth", 0.0008, 0.004)
        g["storage.database_bytes"] = round(self.size_gb * GiB * (1 + growth * days))
        if "storage_full" in self.scenarios:
            used_pct = 96.0 + 1.8 * rnd(s, "stor", 0, 1) + 0.3 * noise(s, "storn", ts, 3600)
        elif "storage_pressure" in self.scenarios:
            used_pct = 91.0 + 2.2 * rnd(s, "stor", 0, 1) + 0.4 * noise(s, "storn", ts, 3600)
        else:
            used_pct = rnd(s, "stor", 42, 74) + 0.5 * noise(s, "storn", ts, 3600)
        g["storage.utilization"] = round(used_pct, 2)
        g["storage.capacity_bytes"] = round(g["storage.database_bytes"] / (used_pct / 100))

        g["availability.up"] = 1.0
        g["uptime.seconds"] = max((ts - self.started_at).total_seconds(), 0)
        g["replication.is_replica"] = 0.0 if self.role == "primary" else 1.0
        if self.role != "primary":
            if "replica_lag" in self.scenarios:  # behind, but within the warning band (60-300 s)
                g["replication.lag_seconds"] = round(signal(s, "lag", ts, 180, amp=0.35, jitter=0.2), 2)
            else:
                g["replication.lag_seconds"] = round(signal(s, "lag", ts, 0.6, amp=0.6, jitter=0.3), 2)
        elif "has_replicas" in self.scenarios:
            g["replication.replica_count"] = 1.0
            g["replication.lag_seconds"] = round(signal(s, "plag", ts, 0.4, amp=0.5), 2)

        waits = self.meta["wait_types"]
        weights = [0.45, 0.25, 0.1 + (0.3 if blocking else 0), 0.1, 0.05, 0.05][: len(waits)]
        if pressure:
            weights[1] += 0.35
        for wt, wgt in zip(waits, weights, strict=False):
            snap.labeled.append(("wait.active_sessions", {"type": wt}, round(max(active * wgt, 0), 2)))

        if self.sim_engine == "postgresql":
            g["pg.idle_in_transaction_longest_seconds"] = round(
                abs(noise(s, "iitl", ts)) * (1800 if blocking else 30), 1
            )
        if self.sim_engine == "oracle":
            g["oracle.sga_used_bytes"] = 8 * GiB * 0.94
            g["oracle.pga_used_bytes"] = round(2 * GiB * (1.1 if pressure else 0.7) * (1 + 0.1 * noise(s, "pga", ts)))
        if self.sim_engine == "db2":
            g["db2.bufferpool_hit_ratio"] = g["cache.hit_ratio"]
            g["db2.lock_escalations"] = 1.0 if blocking and noise(s, "esc", ts) > 0.7 else 0.0
        if self.sim_engine == "mssql":
            g["mssql.page_life_expectancy"] = round(signal(s, "ple", ts, 280 if pressure else 4200, amp=0.3))
            g["mssql.batch_requests_per_sec"] = round(tps * 2.1, 2)
        if self.sim_engine in ("mysql", "mariadb"):
            g["mysql.threads_running"] = round(active)
            g["mysql.tmp_disk_tables_per_sec"] = round(signal(s, "tdt", ts, 9 if temp else 0.2), 2)
        return snap

    def _regression(self, ts: datetime, weight: float = 1.0) -> float:
        """Latency multiplier for the ``regressing_query`` scenario (1.0 when not regressing)."""
        if "regressing_query" not in self.scenarios or self.regression_since is None or ts <= self.regression_since:
            return 1.0
        hours = (ts - self.regression_since).total_seconds() / 3600
        return 1.0 + weight * min(hours * 0.35, 14.0)

    async def get_performance_metrics(self, slow: bool = True) -> MetricSnapshot:
        await self.connect()
        return self.metrics_at(datetime.now(UTC))

