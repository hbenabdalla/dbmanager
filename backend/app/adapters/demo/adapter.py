    def query_stats_at(self, now: datetime, limit: int = 100) -> list[QueryStat]:
        hours_up = max((now - self.started_at).total_seconds() / 3600, 1)
        pressure = 2.4 if "cache_pressure" in self.scenarios else 1.0
        slow = 4.0 if "slow_queries" in self.scenarios else 1.0
        out = []
        tmpl = catalog.QUERY_TEMPLATES.get(self.sim_engine, catalog.QUERY_TEMPLATES["postgresql"])
        dbs = [d for d in self.meta["databases"] if d not in self.meta["system_dbs"]] or self.meta["databases"]
        for i, (text, mean_ms, cpm) in enumerate(tmpl):
            calls = int(cpm * 60 * hours_up * 0.55 * self.scale)
            mean = mean_ms * pressure * (1 + 0.15 * noise(self.seed, f"qm{i}", now, 3600))
            if mean_ms >= 500:
                mean *= slow  # the heavy statements (scans, reports) get slower
            if i == 0:
                mean *= self._regression(now)  # the hot statement regresses in ``regressing_query``
            rows_per = (
                1
                if text.lstrip().upper().startswith(("UPDATE", "INSERT", "DELETE"))
                else int(rnd(self.seed, f"qr{i}", 1, 400))
            )
            reads = int(calls * (mean * 9))
            out.append(
                QueryStat(
                    query_id=str(int(rnd(self.seed, text, 1e15, 9e15))),
                    query_text=text,
                    database=str(pick(self.seed, f"qd{i}", dbs)),
                    username=self.meta["users"][1 + i % 3][0],
                    calls=calls,
                    total_ms=round(calls * mean, 1),
                    mean_ms=round(mean, 3),
                    max_ms=round(mean * rnd(self.seed, f"qx{i}", 3, 25), 1),
                    stddev_ms=round(mean * 0.6, 2),
                    rows=calls * rows_per,
                    cpu_ms=round(calls * mean * 0.6, 1) if self.sim_engine in ("mssql", "oracle", "db2") else None,
                    logical_reads=reads,
                    physical_reads=int(reads * (0.08 if pressure > 1 else 0.006)),
                    temp_blocks=int(calls * 40) if mean_ms > 1000 else 0,
                    lock_wait_ms=round(calls * mean * 0.02, 1) if self.sim_engine in ("mssql", "db2") else None,
                )
            )
        out.sort(key=lambda q: q.total_ms, reverse=True)
        return out[:limit]

    async def explain_query(self, sql: str, database: str | None = None, analyze: bool = False) -> ExplainResult:
        await self.connect()
        tables = re.findall(r"\b(?:from|join|update|into)\s+([A-Za-z_][\w.`\"]*)", sql, re.I)
        tables = [t.strip('`"') for t in tables] or ["dual"]
        big = rnd(self.seed, tables[0], 2e5, 6e7)
        scan_op = {"oracle": "TABLE ACCESS FULL", "db2": "TBSCAN", "mssql": "Clustered Index Scan"}.get(
            self.sim_engine, "Seq Scan"
        )
        has_where = bool(re.search(r"\bwhere\b", sql, re.I))
        node_id = [0]

        def nid() -> int:
            node_id[0] += 1
            return node_id[0]

        def scan(t: str, rows: float) -> PlanNode:
            use_index = len(t) % 2 == 0 and has_where
            est = rows * (0.002 if use_index else (0.3 if has_where else 1))
            return PlanNode(
                id=nid(),
                operator="Index Scan" if use_index else scan_op,
                relation=t,
                index=f"{t}_pkey" if use_index else None,
                total_cost=round(est * (0.02 if use_index else 0.012) + 4, 2),
                estimated_rows=round(est),
                actual_rows=round(est * (40 if not use_index and analyze else 1)) if analyze else None,
                actual_total_ms=round(est * 0.0008, 2) if analyze else None,
                loops=1 if analyze else None,
                filter="(status = 'open'::text)" if has_where and not use_index else None,
                rows_removed_by_filter=round(rows * 0.7) if has_where and not use_index and analyze else None,
                shared_read=int(est * 0.05) if analyze else None,
            )

        children = [scan(t, big / (i + 1)) for i, t in enumerate(tables[:2])]
        if len(children) == 2:
            root_child = PlanNode(
                id=nid(),
                operator="Hash Join (Inner)",
                detail="Hash Cond: (a.id = b.ref_id)",
                total_cost=round(sum(c.total_cost or 0 for c in children) * 1.15, 2),
                estimated_rows=children[1].estimated_rows,
                children=children,
            )
        else:
            root_child = children[0]
        root = root_child
        if re.search(r"\border\s+by\b", sql, re.I):
            root = PlanNode(
                id=nid(),
                operator="Sort",
                detail="Sort Key: created_at DESC",
                total_cost=round((root_child.total_cost or 0) * 1.3, 2),
                estimated_rows=root_child.estimated_rows,
                sort_space_type="Disk"
                if analyze and "temp_spill" in self.scenarios
                else ("Memory" if analyze else None),
                children=[root_child],
            )
        issues = analyze_plan(root, analyzed=analyze)
        return ExplainResult(
            engine=self.sim_engine,
            mode="analyze" if analyze else "estimate",
            executed=False,
            root=root,
            issues=issues,
            total_cost=root.total_cost,
            planning_ms=0.4,
            execution_ms=round(rnd(self.seed, sql, 5, 900), 1) if analyze else None,
            notes=["Simulated plan generated by the demo server — nothing was executed."],
        )

