    def _accounts(self) -> list[DbUser]:
        now = datetime.now(UTC)
        out = []
        for i, (name, admin, reasons, member_of) in enumerate(self.meta["users"]):
            dormant = "hardened" not in self.scenarios and name in (
                "SCOTT",
                "j.smith",
                "RPTUSER",
                "analytics@10.%",
                "etl_svc",
            )
            out.append(
                DbUser(
                    name=name,
                    can_login=True,
                    is_superuser=admin,
                    member_of=list(member_of),
                    admin_reasons=list(reasons),
                    last_login_at=now
                    - timedelta(days=int(rnd(self.seed, name, 120, 400)) if dormant else rnd(self.seed, name, 0, 2)),
                    attributes={"simulated": True},
                    is_system=i == 0 and self.sim_engine in ("oracle", "mssql"),
                )
            )
        for name, member_of in self.meta["roles"]:
            out.append(
                DbUser(
                    name=name,
                    can_login=False,
                    member_of=list(member_of),
                    admin_reasons=["DBA role"] if name in ("DBA", "db_owner") else [],
                )
            )
        return out

    async def list_users(self) -> list[DbUser]:
        await self.connect()
        return [u for u in self._accounts() if u.can_login]

    async def list_roles(self) -> list[DbUser]:
        await self.connect()
        return [u for u in self._accounts() if not u.can_login]

    async def get_privileges(
        self, database: str | None = None, grantee: str | None = None, limit: int = 2000
    ) -> list[Privilege]:
        await self.connect()
        db = database or self.meta["databases"][-1]
        schema = next((k for k, v in self.meta["schemas"].items() if not v), "public")
        out: list[Privilege] = []
        for u in self._accounts():
            if u.is_superuser:
                out.append(
                    Privilege(
                        grantee=u.name,
                        object_type="server",
                        object_name="*",
                        privilege="ALL (administrative)",
                        database=db,
                    )
                )
            for r in u.member_of:
                out.append(Privilege(grantee=u.name, object_type="role", object_name=r, privilege="MEMBER", via_role=r))
        for t in ("orders", "customers", "payments"):
            out.append(
                Privilege(
                    grantee=self.meta["users"][1][0],
                    object_type="table",
                    object_name=f"{schema}.{t}",
                    privilege="SELECT",
                    database=db,
                )
            )
            out.append(
                Privilege(
                    grantee=self.meta["users"][1][0],
                    object_type="table",
                    object_name=f"{schema}.{t}",
                    privilege="UPDATE",
                    database=db,
                )
            )
        out.append(
            Privilege(grantee="PUBLIC", object_type="database", object_name=db, privilege="CONNECT", database=db)
        )
        if grantee:
            out = [p for p in out if p.grantee == grantee]
        return out[:limit]

