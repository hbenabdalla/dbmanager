    async def list_databases(self) -> list[DatabaseInfo]:
        await self.connect()
        dbs = self.meta["databases"]
        user_dbs = [d for d in dbs if d not in self.meta["system_dbs"]] or dbs
        total = self.size_gb * GiB
        out = []
        for d in dbs:
            share = (1 / len(user_dbs)) * rnd(self.seed, d, 0.6, 1.4) if d in user_dbs else 0.002
            out.append(
                DatabaseInfo(
                    name=d,
                    owner=self.meta["users"][0][0],
                    size_bytes=int(total * share),
                    encoding="UTF8",
                    is_system=d in self.meta["system_dbs"],
                    allow_connections=True,
                    extra={
                        "sessions": int(rnd(self.seed, d + "s", 0, 60)) if d in user_dbs else 0,
                        "cache_hit_ratio": round(rnd(self.seed, d + "h", 97.5, 99.9), 2),
                    },
                )
            )
        return out

    async def list_schemas(self, database: str) -> list[SchemaInfo]:
        await self.connect()
        out = []
        for name, is_sys in self.meta["schemas"].items():
            n_tables = 0 if is_sys else len(catalog.TABLES["default"]) - 2
            out.append(
                SchemaInfo(
                    name=name,
                    owner=self.meta["users"][0][0],
                    is_system=is_sys,
                    size_bytes=None if is_sys else int(self.size_gb * GiB * rnd(self.seed, database + name, 0.05, 0.4)),
                    object_counts={
                        "tables": n_tables if not is_sys else int(rnd(self.seed, name, 60, 140)),
                        "views": 0 if is_sys else 1,
                        "materialized_views": 0 if is_sys else 1,
                        "indexes": 0 if is_sys else 14,
                        "sequences": 0 if is_sys else 5,
                        "routines": 0 if is_sys else 6,
                    },
                )
            )
        return out

    def _tables(self, schema: str) -> list[ObjectInfo]:
        out = []
        for t, kind, rows in catalog.TABLES["default"]:
            rows_s = int(rows * self.scale * rnd(self.seed, schema + t, 0.5, 1.5)) if rows else None
            out.append(
                ObjectInfo(
                    name=t if self.sim_engine not in ("oracle", "db2") else t.upper(),
                    schema_name=schema,
                    type=kind,
                    owner=self.meta["users"][1][0],
                    row_estimate=rows_s,
                    size_bytes=int((rows_s or 1000) * 180),
                )
            )
        return out

    async def list_objects(self, database: str, schema: str, object_type: str | None = None) -> list[ObjectInfo]:
        await self.connect()
        if self.meta["schemas"].get(schema, True):
            return []
        objs = self._tables(schema)
        for t in [o for o in objs if o.type == "table"]:
            objs.append(
                ObjectInfo(
                    name=f"{t.name}_pkey",
                    schema_name=schema,
                    type="index",
                    parent=t.name,
                    size_bytes=(t.size_bytes or 0) // 6,
                )
            )
        objs += [
            ObjectInfo(name="orders_id_seq", schema_name=schema, type="sequence"),
            ObjectInfo(
                name="fn_order_total", schema_name=schema, type="function", extra={"arguments": "order_id bigint"}
            ),
            ObjectInfo(name="sp_close_period", schema_name=schema, type="procedure"),
            ObjectInfo(name="trg_orders_audit", schema_name=schema, type="trigger", parent="orders"),
        ]
        if object_type:
            objs = [o for o in objs if o.type == object_type]
        return objs

    async def get_object_detail(self, database: str, schema: str, name: str, object_type: str) -> ObjectDetail:
        objs = [o for o in await self.list_objects(database, schema) if o.name == name]
        if not objs:
            raise AdapterError(f"object {schema}.{name} not found")
        obj = objs[0]
        cols = [
            ColumnInfo(name="id", data_type="bigint", nullable=False, position=1),
            ColumnInfo(name="customer_id", data_type="bigint", nullable=False, position=2),
            ColumnInfo(name="status", data_type="varchar(32)", nullable=False, default="'new'", position=3),
            ColumnInfo(name="total", data_type="numeric(12,2)", nullable=True, position=4),
            ColumnInfo(
                name="created_at", data_type="timestamp with time zone", nullable=False, default="now()", position=5
            ),
        ]
        return ObjectDetail(
            object=obj,
            columns=cols if obj.type in ("table", "view", "materialized_view") else [],
            indexes=[
                {
                    "name": f"{name}_pkey",
                    "definition": f"CREATE UNIQUE INDEX {name}_pkey ON {schema}.{name} (id)",
                    "is_primary": True,
                    "idx_scan": 182_334,
                }
            ],
            constraints=[{"name": f"{name}_pkey", "kind": "primary key", "definition": "PRIMARY KEY (id)"}],
            statistics={"seq_scan": int(rnd(self.seed, name, 10, 9000)), "n_live_tup": obj.row_estimate},
            definition=f"-- simulated definition\nCREATE TABLE {schema}.{name} (\n  id bigint PRIMARY KEY,\n  customer_id bigint NOT NULL,\n"
            "  status varchar(32) NOT NULL DEFAULT 'new',\n  total numeric(12,2),\n  created_at timestamptz NOT NULL DEFAULT now()\n);",
            definition_note="Simulated object (demo server).",
        )

    # ------------------------------------------------------------------------------------
