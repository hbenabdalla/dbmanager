"""Simulation adapter: serves every server whose ``data_source`` is ``simulated``.

Simulated servers are created by the simulation feature (:mod:`app.simulation`). Every value
this adapter returns is generated by :mod:`app.adapters.demo.simulator`: it never opens a
network connection, never uses credentials and never executes SQL, and the API/UI label
these servers as *Simulated*. It exercises the full platform — collectors, rule engines,
dashboards — without Oracle, Db2 or SQL Server being available.

Scenarios (``demo_profile.scenarios``) shape the generated evidence so that health states,
recommendations and security findings are explained by the data:

``connection_saturation``, ``cache_pressure``, ``blocking``, ``deadlocks``, ``temp_spill``,
``high_cpu``, ``cpu_saturation``, ``slow_queries``, ``regressing_query``, ``storage_pressure``,
``storage_full``, ``tablespace_full``, ``replica_lag``, ``has_replicas``, ``weak_security``, ``hardened``,
``outdated_version``, ``down``.
"""

