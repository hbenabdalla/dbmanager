import { FlaskConical } from "lucide-react";
import type { Health, Severity } from "@/api/types";
import { Badge } from "@/components/ui/badge";
import { Tooltip } from "@/components/ui/tooltip";
import { HEALTH_LABEL } from "@/lib/engines";
import { cn } from "@/lib/utils";

export const HEALTH_TONE: Record<string, "ok" | "warn" | "crit" | "down" | "neutral"> = {
  healthy: "ok", warning: "warn", critical: "crit", unavailable: "down", unknown: "neutral",
};
export const HEALTH_VAR: Record<string, string> = {
  healthy: "var(--ok)", warning: "var(--warn)", critical: "var(--crit)", unavailable: "var(--down)", unknown: "var(--border-strong)",
};

export function HealthDot({ health, className }: { health: string; className?: string }) {
  return <span aria-hidden className={cn("inline-block size-2 shrink-0 rounded-full", className)} style={{ background: HEALTH_VAR[health] ?? HEALTH_VAR.unknown }} />;
}

export function HealthBadge({ health, reasons }: { health: Health | string; reasons?: string[] }) {
  const b = (
    <Badge tone={HEALTH_TONE[health] ?? "neutral"}>
      <HealthDot health={health} className="size-1.5" />
      {HEALTH_LABEL[health] ?? health}
    </Badge>
  );
  return reasons && reasons.length ? <Tooltip content={reasons.join("; ")}><span>{b}</span></Tooltip> : b;
}

const SEV_TONE: Record<string, "crit" | "warn" | "info" | "neutral"> = {
  critical: "crit", high: "crit", medium: "warn", low: "info", info: "neutral",
};
const SEV_LABEL: Record<string, string> = { critical: "Critical", high: "High", medium: "Medium", low: "Low", info: "Info" };

export function SeverityBadge({ severity }: { severity: Severity | string }) {
  return (
    <Badge tone={SEV_TONE[severity] ?? "neutral"} className={cn(severity === "critical" && "ring-1 ring-crit/40")}>
      {SEV_LABEL[severity] ?? severity}
    </Badge>
  );
}

export { DatabaseEngineIcon } from "@/components/engine-icon";

export function SimulatedBadge({ className, label = "Simulated" }: { className?: string; label?: string }) {
  return (
    <Tooltip content="Simulated server, generated by a Platform Administrator for demonstration. Every value shown for it is generated; DBManager never connects to it.">
      <span className={cn("inline-flex items-center gap-1 whitespace-nowrap rounded-[5px] border border-dashed border-sim/50 bg-sim-soft px-1.5 text-2xs font-semibold leading-[18px] tracking-wide text-sim", className)}>
        <FlaskConical className="size-3" /> {label}
      </span>
    </Tooltip>
  );
}

export function RiskBadge({ risk }: { risk: string }) {
  const map: Record<string, { tone: "ok" | "info" | "warn" | "crit"; label: string }> = {
    READ: { tone: "ok", label: "Read only" },
    LOW_RISK_CHANGE: { tone: "info", label: "Low-risk change" },
    PRIVILEGED_CHANGE: { tone: "warn", label: "Privileged change" },
    DESTRUCTIVE: { tone: "crit", label: "Destructive" },
  };
  const m = map[risk] ?? { tone: "info" as const, label: risk };
  return <Badge tone={m.tone}>{m.label}</Badge>;
}
